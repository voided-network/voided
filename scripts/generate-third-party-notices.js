#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import {
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const workspaceRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const cratesRoot = join(workspaceRoot, 'crates');

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: cratesRoot,
    encoding: 'utf8',
    ...options,
  });
  if (result.status !== 0) {
    throw new Error(
      `[licenses] ${command} ${args.join(' ')} failed\n` +
        `${result.stdout ?? ''}${result.stderr ?? ''}`,
    );
  }
  return result.stdout.trim();
}

const cargoAboutVersion = run('cargo', ['about', '--version']);
if (cargoAboutVersion !== 'cargo-about 0.9.1') {
  throw new Error(
    `[licenses] expected cargo-about 0.9.1, found ${cargoAboutVersion}`,
  );
}

const scratch = mkdtempSync(join(tmpdir(), 'voided-licenses-'));
try {
  const rustOutput = join(scratch, 'rust-notices.txt');
  run('cargo', [
    'about',
    'generate',
    '--frozen',
    '--workspace',
    '--all-features',
    '--fail',
    '--config',
    join(cratesRoot, 'about.toml'),
    '--output-file',
    rustOutput,
    join(cratesRoot, 'about.hbs'),
  ]);
  const rustNotices = readFileSync(rustOutput, 'utf8').trim();
  if (!rustNotices.includes('MIT License') || !rustNotices.includes('Used by:')) {
    throw new Error('[licenses] generated Rust notices are incomplete');
  }

  const npmPackages = [
    { name: 'qrcode', licenseFile: 'license' },
    { name: 'fflate', licenseFile: 'LICENSE' },
  ];
  const npmNotices = npmPackages.map(({ name, licenseFile }) => {
    const packageRoot = join(workspaceRoot, 'node_modules', name);
    const metadata = JSON.parse(
      readFileSync(join(packageRoot, 'package.json'), 'utf8'),
    );
    if (metadata.name !== name || metadata.license !== 'MIT') {
      throw new Error(`[licenses] unexpected ${name} package metadata`);
    }
    const license = readFileSync(join(packageRoot, licenseFile), 'utf8').trim();
    return [
      '-------------------------------------------------------------------------------',
      `${metadata.name} ${metadata.version} (MIT)`,
      metadata.repository
        ? `Source: ${typeof metadata.repository === 'string'
            ? metadata.repository
            : metadata.repository.url}`
        : null,
      '',
      license,
    ].filter((line) => line !== null).join('\n');
  }).join('\n\n');

  const header = [
    'VOIDED THIRD-PARTY SOFTWARE NOTICES',
    '',
    'Generated by scripts/generate-third-party-notices.js. Do not hand-edit.',
    'The Voided license is provided separately in LICENSE.',
    '',
  ].join('\n');
  const rustDocument = `${header}RUST DEPENDENCIES\n\n${rustNotices}\n`;
  const browserDocument =
    `${header}BUNDLED JAVASCRIPT DEPENDENCIES\n\n${npmNotices}\n\n` +
    `RUST/WASM DEPENDENCIES\n\n${rustNotices}\n`;

  writeFileSync(
    join(workspaceRoot, 'packages', 'e2ee-client', 'THIRD_PARTY_NOTICES'),
    browserDocument,
  );
  writeFileSync(
    join(workspaceRoot, 'packages', 'enc-server', 'THIRD_PARTY_NOTICES'),
    rustDocument,
  );
  writeFileSync(
    join(cratesRoot, 'voided-core', 'THIRD_PARTY_NOTICES'),
    rustDocument,
  );
  console.log('[licenses] generated npm, native, WASM, and core notices');
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
